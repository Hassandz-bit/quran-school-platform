export function normalizeLocale(value: unknown): AppLocale | null {
  return value === "ar" || value === "en" ? value : null;
}

export function getDirection(locale: AppLocale): AppDirection {
  return locale === "ar" ? "rtl" : "ltr";
}

export function translate(locale: AppLocale, key: TranslationKey): string {
  return locale === "en" ? EN_MESSAGES[key] : AR_MESSAGES[key];
}
