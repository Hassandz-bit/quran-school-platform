const ARABIC_RE = /[\u0600-\u06ff]/;

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

export function translateVisibleText(value: string, locale: AppLocale): string {
  if (locale !== "en" || !ARABIC_RE.test(value)) return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const core = value.trim();
  const exact = EXACT_ENGLISH[core];
  if (exact) return `${leading}${exact}${trailing}`;

  let translated = core;
  for (const [arabic, english] of PHRASE_ENGLISH) {
    // Arabic words are not covered reliably by JavaScript's `\b`. Explicit
    // Arabic-script boundaries prevent fragments such as "تم" from changing
    // the middle of a person's or school's name.
    const safePhrase = new RegExp(
      `(?<![\\u0600-\\u06ff])${escapeRegExp(arabic)}(?![\\u0600-\\u06ff])`,
      "gu"
    );
    translated = translated.replace(safePhrase, english);
  }
  return translated === core ? value : `${leading}${translated}${trailing}`;
}
